    // MARK: GL / MTL HwInfo shader-engine count

    /// `gfx9_HwInfoInitData` selects a family tier by comparing the HwInfo value
    /// against thresholds and then stores the shader-engine count (4 for Vega10)
    /// into `rec+0x78`. Renoir-family APUs have one shader engine, so the *lowest
    /// tier's* store is rewritten to 1. The tier is derived from the CFG guard
    /// immediate (minimum threshold), never from a hardcoded address.
    private static let shaderEngineCountGL = SemanticRule(
        id: "gfx9.hwinfo.shader_engine_count",
        driver: .gl,
        description: "GL driver gfx9 HwInfo: report the APU shader-engine count (1) instead of the Vega10 count (4)",
        functions: [
            RuleFunctionTarget(description: "GL _gfx9_HwInfoInitData",
                               resolve: { image, decoder in
                                   try FunctionResolution.bySymbol("_gfx9_HwInfoInitData", in: image, decoder: decoder)
                               },
                               expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            try matchShaderEngineCount(analysis, decoder: decoder)
        }
    )

    private static let shaderEngineCountMTL = SemanticRule(
        id: "gfx9.hwinfo.shader_engine_count.metal",
        driver: .mtl,
        description: "Metal driver gfx9 HwInfo: report the APU shader-engine count (1) instead of the Vega10 count (4)",
        functions: [
            RuleFunctionTarget(description: "Metal gfx9_HwInfoInitData",
                               resolve: { image, decoder in
                                   try FunctionResolution.bySymbol(
                                       "__Z19gfx9_HwInfoInitDataP14GFX9_HwInfoRecP24_sAMD_GET_HW_INFO_VALUESj",
                                       in: image, decoder: decoder)
                               },
                               expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            try matchShaderEngineCount(analysis, decoder: decoder)
        }
    )

    private static func matchShaderEngineCount(_ analysis: FunctionAnalysis,
                                               decoder: X86Decoder) throws -> [SiteMatch] {
        // Candidate stores: `mov dword ptr [reg + 0x78], imm32` where imm is the
        // hardware shader-engine count. Multiple family tiers store such a value;
        // the controlling guard comparison identifies the tier.
        struct Candidate {
            let index: Int
            let instruction: DecodedInstruction
            let register: Register
            let immediate: Int64
            let guardValue: Int64?
        }
        var candidates: [Candidate] = []
        for (index, instruction) in analysis.instructions.enumerated() {
            guard instruction.mnemonic == "mov", let parsed = instruction.parsed,
                  parsed.operands.count == 2,
                  let memory = parsed.operand0?.memory, memory.size == 32,
                  let base = memory.base, base.isGeneralPurpose, memory.index == nil,
                  memory.displacement == 0x78,
                  let immediate = parsed.operand1?.immediate,
                  immediate > 0, immediate <= 32 else {
                continue
            }
            var guardValues: Set<Int64> = []
            if let blockIndex = analysis.blockIndex(containing: instruction.address) {
                let candidateBlockStart = analysis.blocks[blockIndex].start
                for predecessor in analysis.predecessors(ofBlock: blockIndex) {
                    let predecessorInstructions = analysis.instructions(inBlock: predecessor)
                    guard let terminator = predecessorInstructions.last, terminator.isConditionalBranch,
                          let target = terminator.directBranchTarget,
                          target != candidateBlockStart else {
                        // Only the fall-through path selects the candidate block; a
                        // branch-target path would need inverted guard semantics.
                        continue
                    }
                    for guardInstruction in predecessorInstructions {
                        guard guardInstruction.mnemonic == "cmp", let parsedCandidate = guardInstruction.parsed,
                              parsedCandidate.operands.count == 2,
                              parsedCandidate.operand0?.register?.width == 32,
                              let rhs = parsedCandidate.operand1?.immediate else { continue }
                        guardValues.insert(rhs)
                    }
                }
            }
            let guardValue: Int64? = guardValues.count == 1 ? guardValues.first : nil
            candidates.append(Candidate(index: index, instruction: instruction,
                                        register: base, immediate: immediate, guardValue: guardValue))
        }
        guard !candidates.isEmpty else {
            throw AnalyzerError.notFound("\(analysis.imageLabel): shader-engine count store in \(analysis.functionName)")
        }
        let guarded = candidates.filter { $0.guardValue != nil }
        guard guarded.count == candidates.count else {
            throw AnalyzerError.ambiguous("\(analysis.imageLabel): shader-engine store without a family-tier guard")
        }
        guard let minimumGuard = guarded.compactMap(\.guardValue).min() else {
            throw AnalyzerError.ambiguous("\(analysis.imageLabel): no family-tier guard value")
        }
        let selected = guarded.filter { $0.guardValue == minimumGuard }
        guard selected.count == 1, let candidate = selected.first else {
            throw AnalyzerError.ambiguous(
                "\(analysis.imageLabel): \(selected.count) shader-engine stores for the lowest family tier")
        }
        guard candidate.immediate != 1 else {
            throw AnalyzerError.validation(
                "\(analysis.imageLabel): shader-engine count is already 1 at \(Hex.value(candidate.instruction.address))")
        }
        guard let replacement = ReplacementEncoding.replaceImmediate32(
            in: candidate.instruction.bytes, oldValue: UInt32(candidate.immediate), newValue: 1) else {
            throw AnalyzerError.validation("cannot rewrite shader-engine immediate")
        }
        let decoded = try ReplacementEncoding.decodeValidated(decoder, bytes: replacement,
                                                              address: candidate.instruction.address)
        guard decoded.count == 1, decoded[0].mnemonic == "mov",
              decoded[0].parsed?.operand1?.immediate == 1 else {
            throw AnalyzerError.validation("shader-engine replacement does not decode to the intended store")
        }
        return [SiteMatch(function: analysis,
                          instructionAddresses: [candidate.instruction.address],
                          find: candidate.instruction.bytes,
                          replace: replacement,
                          intent: "store shader-engine count 1 in the lowest gfx9 family tier (was \(candidate.immediate))",
                          matchedInstruction: candidate.instruction.text)]
    }

    // MARK: GL dual-quad

    private static let dualQuadMode = SemanticRule(
        id: "gfx9.dualquad.force_disable",
        driver: .gl,
        description: "GL _glrAMD_GFX9_UpdateHwCbDualQuadMode: force CB_COLOR_CONTROL.DISABLE_DUAL_QUAD on the iGPU",
        functions: [
            RuleFunctionTarget(description: "GL _glrAMD_GFX9_UpdateHwCbDualQuadMode",
                               resolve: { image, decoder in
                                   try FunctionResolution.bySymbol("_glrAMD_GFX9_UpdateHwCbDualQuadMode",
                                                                   in: image, decoder: decoder)
                               },
                               expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            // The driver clears the dual-quad disable bit with `and reg, ~1`; the
            // fix forces it set with a same-length `or reg, 1`.
            var matches: [(Int, DecodedInstruction, Register)] = []
            for (index, instruction) in analysis.instructions.enumerated() {
                guard instruction.mnemonic == "and", let parsed = instruction.parsed,
                      parsed.operands.count == 2,
                      let register = parsed.operand0?.register, register.width == 32,
                      let immediate = parsed.operand1?.immediate,
                      immediate >= 0,
                      (immediate & 1) == 0,
                      (immediate | 1) == 0xffff_ffff else {
                    continue
                }
                matches.append((index, instruction, register))
            }
            guard matches.count == 1, let match = matches.first else {
                throw AnalyzerError.ambiguous(
                    "\(analysis.imageLabel): \(matches.count) dual-quad clear instructions in \(analysis.functionName)")
            }
            let instruction = match.1
            let register = match.2
            let replacement = ReplacementEncoding.orImmediate(register, 1)
            guard replacement.count == instruction.length else {
                throw AnalyzerError.validation("dual-quad replacement length differs from the original instruction")
            }
            let decoded = try ReplacementEncoding.decodeValidated(decoder, bytes: replacement,
                                                                  address: instruction.address)
            guard decoded.count == 1, decoded[0].mnemonic == "or",
                  decoded[0].parsed?.operand1?.immediate == 1,
                  decoded[0].parsed?.operand0?.register?.name == register.name else {
                throw AnalyzerError.validation("dual-quad replacement does not decode to `or reg, 1`")
            }
            return [SiteMatch(function: analysis,
                              instructionAddresses: [instruction.address],
                              find: instruction.bytes,
                              replace: replacement,
                              intent: "set CB_COLOR_CONTROL.DISABLE_DUAL_QUAD instead of clearing it",
                              matchedInstruction: instruction.text)]
        }
    )

    // MARK: Metal RB+ gate

    private static let metalRBPlusGate = SemanticRule(
        id: "metal.rbplus.open_gate",
        driver: .mtl,
        description: "Metal pipeline setup: open the RB+ gate so normal pipelines keep RB+ enabled",
        functions: [
            RuleFunctionTarget(
                description: "-[GFX9_MtlRenderPipelineState initWithDevice:pipelineStateDescriptor:vertexVariant:fragmentVariant:]",
                resolve: { image, decoder in
                    try FunctionResolution.byObjCMethod(
                        className: "GFX9_MtlRenderPipelineState",
                        selector: "initWithDevice:pipelineStateDescriptor:vertexVariant:fragmentVariant:",
                        in: image, decoder: decoder)
                },
                expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            var matches: [DecodedInstruction] = []
            for instruction in analysis.instructions where instruction.isConditionalBranch && instruction.length == 2 {
                guard let target = instruction.directBranchTarget,
                      let targetBlockIndex = analysis.blockIndex(forStart: target) else { continue }
                let targetBlock = analysis.instructions(inBlock: targetBlockIndex)
                let targetHasSetne = targetBlock.prefix(4).contains { candidate in
                    guard candidate.mnemonic.hasPrefix("set"), let parsed = candidate.parsed else { return false }
                    return parsed.mnemonic == "setne"
                }
                guard targetHasSetne else { continue }
                guard let fallthroughInstruction = analysis.nextInstruction(after: instruction),
                      let fallthroughBlockIndex = analysis.blockIndex(containing: fallthroughInstruction.address) else { continue }
                let fallthroughBlock = analysis.instructions(inBlock: fallthroughBlockIndex)
                guard let first = fallthroughBlock.first, first.mnemonic == "xor",
                      let parsed = first.parsed, parsed.operands.count == 2,
                      let lhs = parsed.operand0?.register, let rhs = parsed.operand1?.register,
                      lhs.name == rhs.name else {
                    continue
                }
                matches.append(instruction)
            }
            guard matches.count == 1, let instruction = matches.first,
                  let target = instruction.directBranchTarget else {
                throw AnalyzerError.ambiguous(
                    "\(analysis.imageLabel): \(matches.count) RB+ gate branches in \(analysis.functionName)")
            }
            var replacement = instruction.bytes
            replacement[0] = 0xeb
            let decoded = try ReplacementEncoding.decodeValidated(decoder, bytes: replacement,
                                                                  address: instruction.address)
            guard decoded.count == 1, decoded[0].isJump, decoded[0].directBranchTarget == target else {
                throw AnalyzerError.validation("RB+ gate replacement is not an unconditional jump to the same block")
            }
            return [SiteMatch(function: analysis,
                              instructionAddresses: [instruction.address],
                              find: instruction.bytes,
                              replace: replacement,
                              intent: "make the RB+ gate unconditional (jcc -> jmp to the RB+ configuration block)",
                              matchedInstruction: instruction.text)]
        }
    )

    // MARK: Metal RB+ allow

    private static let metalRBPlusAllow = SemanticRule(
        id: "metal.rbplus.allow",
        driver: .mtl,
        description: "Metal pipeline setup: treat RB+ as allowed (setcc result -> zero register)",
        functions: [
            RuleFunctionTarget(
                description: "-[GFX9_MtlRenderPipelineState initWithDevice:pipelineStateDescriptor:vertexVariant:fragmentVariant:]",
                resolve: { image, decoder in
                    try FunctionResolution.byObjCMethod(
                        className: "GFX9_MtlRenderPipelineState",
                        selector: "initWithDevice:pipelineStateDescriptor:vertexVariant:fragmentVariant:",
                        in: image, decoder: decoder)
                },
                expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            // Find the RB+ capability test as an instruction triple in one block:
            //   movabs reg, 0x400000000
            //   test <operand>, reg
            //   setcc dst
            // The movabs/test pair immediately before the setcc identifies the RB+
            // capability decision (the other 0x400000000 test in this method jumps
            // away instead of materialising a flag with setcc).
            var matches: [(DecodedInstruction, Register)] = []
            for block in analysis.blocks {
                let instructions = Array(analysis.instructions(inBlock: block.index))
                guard instructions.count >= 3 else { continue }
                for index in 0...(instructions.count - 3) {
                    let load = instructions[index]
                    let test = instructions[index + 1]
                    let setcc = instructions[index + 2]
                    guard load.mnemonic == "movabs", let parsedLoad = load.parsed,
                          parsedLoad.operands.count == 2,
                          parsedLoad.operand1?.immediate == 0x4_0000_0000,
                          let capabilityRegister = parsedLoad.operand0?.register,
                          test.mnemonic == "test", let parsedTest = test.parsed,
                          parsedTest.operands.count == 2,
                          parsedTest.operand0 != nil,
                          parsedTest.operand1?.register?.name == capabilityRegister.name,
                          setcc.mnemonic.hasPrefix("set"), let parsedSetcc = setcc.parsed,
                          parsedSetcc.operands.count == 1,
                          let destination = parsedSetcc.operand0?.register, destination.width == 8 else {
                        continue
                    }
                    matches.append((setcc, destination))
                }
            }
            guard matches.count == 1, let (instruction, register) = matches.first else {
                throw AnalyzerError.ambiguous(
                    "\(analysis.imageLabel): \(matches.count) RB+ allow setcc instructions in "
                        + "\(analysis.functionName) at \(matches.map { Hex.value($0.0.address) })")
            }
            var replacement = ReplacementEncoding.xorSelf(register)
            guard replacement.count <= instruction.length else {
                throw AnalyzerError.validation("RB+ allow replacement does not fit the original instruction")
            }
            while replacement.count < instruction.length { replacement.append(0x90) }
            let decoded = try ReplacementEncoding.decodeValidated(decoder, bytes: replacement,
                                                                  address: instruction.address)
            guard decoded.count >= 1, decoded[0].mnemonic == "xor",
                  decoded[0].parsed?.operand0?.register?.name == decoded[0].parsed?.operand1?.register?.name else {
                throw AnalyzerError.validation("RB+ allow replacement does not decode to a register self-xor")
            }
            return [SiteMatch(function: analysis,
                              instructionAddresses: [instruction.address],
                              find: instruction.bytes,
                              replace: replacement,
                              intent: "treat RB+ as allowed by zeroing the capability setcc destination",
                              matchedInstruction: instruction.text)]
        }
    )

