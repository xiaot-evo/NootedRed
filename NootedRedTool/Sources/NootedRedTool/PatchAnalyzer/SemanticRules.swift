// MARK: - Rule model

enum DriverImage: String, CaseIterable {
    case gl = "AMDRadeonX5000GLDriver"
    case mtl = "AMDRadeonX5000MTLDriver"
    case vda = "AMDRadeonVADriver2"
    case gva = "AppleGVA"

    /// Path suffix used to find the image inside the dyld shared cache.
    var cachePathSuffix: String { rawValue }

    var isStandaloneFile: Bool { self == .gl }

    var bundlePath: String {
        switch self {
        case .gl:
            return "System/Library/Extensions/AMDRadeonX5000GLDriver.bundle/Contents/MacOS/AMDRadeonX5000GLDriver"
        case .mtl:
            return "System/Library/Extensions/AMDRadeonX5000MTLDriver.bundle/Contents/MacOS/AMDRadeonX5000MTLDriver"
        case .vda:
            return "System/Library/Extensions/AMDRadeonVADriver2.bundle/Contents/MacOS/AMDRadeonVADriver2"
        case .gva:
            return "System/Library/PrivateFrameworks/AppleGVA.framework/Versions/A/AppleGVA"
        }
    }
}

/// One instruction-level patch discovered by a rule. All bytes are taken from
/// the parsed target image; `replace` is generated by a semantic transform that
/// must produce a same-length, decodable replacement whose effect is verified.
struct SiteMatch {
    let function: FunctionAnalysis
    let instructionAddresses: [UInt64]
    let find: [UInt8]
    let replace: [UInt8]
    /// Human-readable semantic intent, included verbatim in the JSON evidence.
    let intent: String
    /// The decoded instruction(s) before the patch, included in the evidence.
    let matchedInstruction: String
    /// Structured candidate/derivation evidence for the JSON report.
    var details: [String: String] = [:]
}

/// A rule resolves one or more functions, matches exactly the declared number of
/// unambiguous sites per function and synthesises the replacement bytes.
struct SemanticRule {
    let id: String
    let driver: DriverImage
    let description: String
    let functions: [RuleFunctionTarget]
    let match: (FunctionAnalysis, X86Decoder, [String]) throws -> [SiteMatch]
}

struct RuleFunctionTarget {
    let description: String
    let resolve: (AnalyzedImage, X86Decoder) throws -> [FunctionAnalysis]
    /// Number of sites this target must produce; always 1 for the current rules.
    let expectedSites: Int
}

// MARK: - Function resolution

enum FunctionResolution {
    /// Resolves one function by exact symbol name. Duplicate symbol entries with
    /// different addresses are an ambiguity error.
    static func bySymbol(_ name: String, in image: AnalyzedImage, decoder: X86Decoder) throws -> [FunctionAnalysis] {
        let symbols = image.symbolsByName[name] ?? []
        guard !symbols.isEmpty else {
            throw AnalyzerError.notFound("\(image.label): symbol \(name)")
        }
        let addresses = Set(symbols.filter(\.isDefined).map(\.value))
        guard addresses.count == 1, let address = addresses.first else {
            throw AnalyzerError.ambiguous("\(image.label): symbol \(name) has \(addresses.count) definitions")
        }
        return [try FunctionAnalyzer.analyze(image: image, name: name, address: address, decoder: decoder)]
    }

    /// Resolves an Objective-C method. The exact `-[Class selector]` symbol is
    /// preferred; if it is absent the parsed ObjC metadata supplies the IMP.
    static func byObjCMethod(className: String, selector: String,
                             in image: AnalyzedImage, decoder: X86Decoder) throws -> [FunctionAnalysis] {
        let displayName = "-[\(className) \(selector)]"
        if let symbols = image.symbolsByName[displayName] {
            let addresses = Set(symbols.filter(\.isDefined).map(\.value))
            if addresses.count == 1, let address = addresses.first {
                return [try FunctionAnalyzer.analyze(image: image, name: displayName, address: address, decoder: decoder)]
            }
            throw AnalyzerError.ambiguous("\(image.label): \(displayName) has \(addresses.count) definitions")
        }
        guard let method = ObjectiveCMetadata.method(in: image, className: className, selector: selector) else {
            throw AnalyzerError.notFound("\(image.label): ObjC method \(displayName)")
        }
        return [try FunctionAnalyzer.analyze(image: image, name: displayName, address: method.imp, decoder: decoder)]
    }

    /// Parsed functions and skipped entries of the last image-wide scan, for
    /// evidence output. Only read by the single-threaded generator.
    static private(set) var lastImageScanReport: [String: Any] = [:]

    /// Parses every function that the strict CFG validator can accept. Functions
    /// whose extent contains non-code data (x86_64 jump tables live inside
    /// `__TEXT` between functions) are skipped and recorded in the evidence; the
    /// rule using the scan still fails closed unless exactly one parsed function
    /// carries the semantic pattern.
    static func allFunctions(in image: AnalyzedImage, decoder: X86Decoder) throws -> [FunctionAnalysis] {
        guard let starts = image.functionStarts else {
            throw AnalyzerError.notFound("\(image.label): no LC_FUNCTION_STARTS for image-wide scan")
        }
        var functions: [FunctionAnalysis] = []
        functions.reserveCapacity(starts.starts.count)
        var skipped: [String] = []
        var skipReasons: [String] = []
        for start in starts.starts {
            do {
                let analysis = try FunctionAnalyzer.analyze(image: image, name: "function_\(Hex.value(start))",
                                                            address: start, decoder: decoder)
                functions.append(analysis)
            } catch {
                skipped.append(Hex.value(start))
                if skipReasons.count < 24 {
                    skipReasons.append("\(Hex.value(start)): \(error)")
                }
            }
        }
        lastImageScanReport = [
            "image": image.label,
            "functionStarts": starts.starts.count,
            "parsed": functions.count,
            "skippedNonCode": skipped.count,
            "skippedStarts": skipped,
            "skippedReasons": skipReasons
        ]
        return functions
    }
}

// MARK: - Instruction helpers

enum InstructionMatch {
    static func parse(_ instruction: DecodedInstruction) throws -> ParsedInstruction {
        guard let parsed = instruction.parsed else {
            throw AnalyzerError.unsupported("cannot parse operands of \(instruction.text)")
        }
        return parsed
    }

    static func isRegisterOperand(_ operand: Operand?, width: Int? = nil, base: String? = nil) -> Bool {
        guard let register = operand?.register else { return false }
        if let width, register.width != width { return false }
        if let base, register.name != base { return false }
        return true
    }

    static func isMemoryOperand(_ operand: Operand?, size: Int? = nil, base: String? = nil,
                                displacement: Int64? = nil) -> Bool {
        guard let memory = operand?.memory else { return false }
        if let size, memory.size != size { return false }
        if let base {
            guard let register = memory.base, register.name == base else { return false }
        }
        if let displacement, memory.displacement != displacement { return false }
        return true
    }

    static func immediate(_ operand: Operand?) -> Int64? { operand?.immediate }
}

// MARK: - Replacement encoding helpers

enum ReplacementEncoding {
    /// `xor r32, r32` for the 32-bit register that owns an 8-bit setcc destination.
    static func xorSelf(_ register: Register) -> [UInt8] {
        let code = register.code & 7
        let modrm = UInt8(0xC0 | (code << 3) | code)
        if register.code >= 8 {
            return [0x45, 0x31, modrm]
        }
        return [0x31, modrm]
    }

    /// `or r32, imm8` (opcode 83 /1).
    static func orImmediate(_ register: Register, _ value: UInt8) -> [UInt8] {
        let code = register.code & 7
        var bytes: [UInt8] = []
        if register.code >= 8 { bytes.append(0x41) }
        bytes.append(0x83)
        bytes.append(UInt8(0xC8 | code))
        bytes.append(value)
        return bytes
    }

    /// `mov r32, imm32`.
    static func movImmediate32(_ register: Register, _ value: UInt32) -> [UInt8] {
        var bytes: [UInt8] = []
        if register.code >= 8 { bytes.append(0x41) }
        bytes.append(UInt8(0xB8 | (register.code & 7)))
        bytes.append(UInt8(value & 0xff))
        bytes.append(UInt8((value >> 8) & 0xff))
        bytes.append(UInt8((value >> 16) & 0xff))
        bytes.append(UInt8((value >> 24) & 0xff))
        return bytes
    }

    /// Replaces a 32-bit immediate inside an existing instruction's bytes.
    static func replaceImmediate32(in instructionBytes: [UInt8], oldValue: UInt32, newValue: UInt32) -> [UInt8]? {
        let needle = [UInt8(oldValue & 0xff), UInt8((oldValue >> 8) & 0xff),
                      UInt8((oldValue >> 16) & 0xff), UInt8((oldValue >> 24) & 0xff)]
        var positions: [Int] = []
        if instructionBytes.count >= 4 {
            for start in 0...(instructionBytes.count - 4) where Array(instructionBytes[start..<(start + 4)]) == needle {
                positions.append(start)
            }
        }
        guard positions.count == 1, let position = positions.first else { return nil }
        var result = instructionBytes
        result[position] = UInt8(newValue & 0xff)
        result[position + 1] = UInt8((newValue >> 8) & 0xff)
        result[position + 2] = UInt8((newValue >> 16) & 0xff)
        result[position + 3] = UInt8((newValue >> 24) & 0xff)
        return result
    }

    static func decodeValidated(_ decoder: X86Decoder, bytes: [UInt8], address: UInt64) throws -> [DecodedInstruction] {
        let decoded = try decoder.decode(bytes: bytes, address: address)
        guard !decoded.isEmpty, decoded.reduce(0) { $0 + $1.length } == bytes.count else {
            throw AnalyzerError.validation("replacement bytes do not decode cleanly at \(Hex.value(address))")
        }
        return decoded
    }
}

