    /// `AVDGetGPUAccelerators` has no exported symbol in the 24H232 cache, so the
    /// rule resolves it from the parsed image: the function must contain both
    ///   (a) the AMD-accelerator insertion tail
    ///       `mov qword [rbx+8], reg; mov qword [rbx+0x10], reg2; cmp; jcc;
    ///        mov reg3, [rbp-0x130]; mov [reg], reg3`
    ///       (the caller-collected AMD accelerator is stored into the output
    ///       vector after a capacity check), and
    ///   (b) exactly one null-return guard
    ///       `test r64, r64; je <empty-return>` whose fall-through path also
    ///       jumps to the same empty-return block (the "no Intel accelerator"
    ///       path returns an empty list today).
    /// The patch redirects that guard to the AMD insertion tail, exactly the
    /// mainline pin: "no Intel accelerator + non-special board-id ⇒ return the
    /// AMD accelerator already collected at [rbp-0x130]".
    private static let appleGVAAcceleratorFallback = SemanticRule(
        id: "applegva.avd.amd_accelerator_fallback",
        driver: .gva,
        description: "AppleGVA AVDGetGPUAccelerators: when no Intel accelerator is present, return the "
            + "collected AMD accelerator instead of an empty list",
        functions: [
            RuleFunctionTarget(description: "AVDGetGPUAccelerators (symbol-less local function)",
                               resolve: { image, decoder in
                                   let functions = try FunctionResolution.allFunctions(in: image, decoder: decoder)
                                   var candidates: [FunctionAnalysis] = []
                                   var rejected: [String] = []
                                   for function in functions {
                                       guard let insertionStart = Self.amdInsertionStart(function) else {
                                           continue
                                       }
                                       let sites = Self.acceleratorEmptyReturnBranches(function)
                                       guard sites.count == 1 else { continue }
                                       candidates.append(function)
                                       _ = insertionStart
                                   }
                                   if ProcessInfo.processInfo.environment["NRED_ANALYZER_DEBUG"] != nil {
                                       let addresses = candidates.map { Hex.value($0.start) }.joined(separator: ",")
                                       let line = "GVA AVD scan: parsed=\(functions.count) "
                                           + "candidates=\(candidates.count) [\(addresses)] "
                                           + "rejectedWithInsertionNoUniqueGuard=\(rejected.count)\n"
                                       FileHandle.standardError.write(Data(line.utf8))
                                       for function in functions {
                                           let hasAcceleratorLoad = function.instructions.contains { instruction in
                                               instruction.parsed?.operand1?.memory?.displacement == -0x130
                                           }
                                           guard hasAcceleratorLoad else { continue }
                                           let insertion = Self.amdInsertionStart(function).map(Hex.value) ?? "nil"
                                           let branches = Self.acceleratorEmptyReturnBranches(function)
                                           let branchList = branches.map { Hex.value($0.address) }.joined(separator: ",")
                                           let detail = "  fn \(Hex.value(function.start)) insertion=\(insertion) "
                                               + "branches=\(branches.count) [\(branchList)]\n"
                                           FileHandle.standardError.write(Data(detail.utf8))
                                       }
                                       if let report = FunctionResolution.lastImageScanReport as? [String: Any],
                                          let skipped = report["skippedNonCode"] as? Int {
                                           FileHandle.standardError.write(Data(
                                               "  image scan skipped non-code extents: \(skipped)\n".utf8))
                                       }
                                   }
                                   guard candidates.count == 1 else {
                                       throw AnalyzerError.ambiguous(
                                           "\(image.label): \(candidates.count) AVDGetGPUAccelerators candidates "
                                               + "(\(candidates.map { Hex.value($0.start) }))")
                                   }
                                   return candidates
                               },
                               expectedSites: 1)
        ],
        match: { analysis, decoder, _ in
            guard let insertionStart = Self.amdInsertionStart(analysis) else {
                throw AnalyzerError.notFound(
                    "\(analysis.imageLabel): AMD accelerator insertion sequence in \(analysis.functionName)")
            }
            let candidates = Self.acceleratorEmptyReturnBranches(analysis)
            guard candidates.count == 1, let instruction = candidates.first,
                  let emptyReturnTarget = instruction.directBranchTarget else {
                throw AnalyzerError.ambiguous(
                    "\(analysis.imageLabel): \(candidates.count) accelerator empty-return branches in "
                        + "\(analysis.functionName) at \(candidates.map { Hex.value($0.address) })")
            }
            guard let insertionInstruction = analysis.instruction(at: insertionStart) else {
                throw AnalyzerError.malformed("AMD insertion target is not an instruction boundary")
            }
            guard insertionStart != emptyReturnTarget else {
                throw AnalyzerError.validation(
                    "accelerator fallback target already equals the AMD insertion sequence")
            }
            let displacement = Int64(insertionStart) - Int64(instruction.endAddress)
            guard displacement >= Int64(Int32.min), displacement <= Int64(Int32.max) else {
                throw AnalyzerError.validation("accelerator fallback branch displacement out of range")
            }
            var replacement = instruction.bytes
            let value = Int32(displacement)
            replacement[2] = UInt8(truncatingIfNeeded: value)
            replacement[3] = UInt8(truncatingIfNeeded: value >> 8)
            replacement[4] = UInt8(truncatingIfNeeded: value >> 16)
            replacement[5] = UInt8(truncatingIfNeeded: value >> 24)
            let decoded = try ReplacementEncoding.decodeValidated(decoder, bytes: replacement,
                                                                  address: instruction.address)
            guard decoded.count == 1, decoded[0].directBranchTarget == insertionStart else {
                throw AnalyzerError.validation("accelerator fallback replacement has the wrong target")
            }
            var details: [String: String] = [
                "functionStart": Hex.value(analysis.start),
                "functionEnd": Hex.value(analysis.end),
                "emptyReturnBranch": Hex.value(instruction.address),
                "emptyReturnTarget": Hex.value(emptyReturnTarget),
                "amdInsertionStart": Hex.value(insertionStart),
                "amdInsertionInstruction": insertionInstruction.text,
                "replacementDisplacement": Hex.value(UInt64(bitPattern: Int64(displacement)))
            ]
            details["candidateFunctions"] = "1"
            return [SiteMatch(function: analysis,
                              instructionAddresses: [instruction.address],
                              find: instruction.bytes,
                              replace: replacement,
                              intent: "when no Intel accelerator is present, continue at the AMD accelerator "
                                  + "insertion tail (collected at [rbp-0x130]) instead of returning an empty list",
                              matchedInstruction: instruction.text,
                              details: details)]
        }
    )

    /// Locates the AMD accelerator insertion tail: an output-vector capacity check
    /// (`mov reg,[rbx+8]; mov reg2,[rbx+0x10]; cmp; jcc`) followed by the load of
    /// the collected AMD accelerator (`mov reg3,[rbp-0x130]`) and its store into
    /// the vector (`mov [reg], reg3`). Returns the start of that tail.
    private static func amdInsertionStart(_ analysis: FunctionAnalysis) -> UInt64? {
        let instructions = analysis.instructions
        guard instructions.count > 8 else { return nil }
        var starts: Set<UInt64> = []
        for index in 0..<(instructions.count - 5) {
            let loadBase = instructions[index]
            let loadEnd = instructions[index + 1]
            let compare = instructions[index + 2]
            let branch = instructions[index + 3]
            guard loadBase.mnemonic == "mov", let parsedBase = loadBase.parsed,
                  parsedBase.operands.count == 2,
                  let vectorRegister = parsedBase.operand0?.register, vectorRegister.width == 64,
                  let baseMemory = parsedBase.operand1?.memory, baseMemory.size == 64,
                  baseMemory.base?.name == "rbx", baseMemory.index == nil,
                  baseMemory.displacement == 8,
                  loadEnd.mnemonic == "mov", let parsedEnd = loadEnd.parsed,
                  parsedEnd.operands.count == 2,
                  parsedEnd.operand0?.register?.width == 64,
                  let endMemory = parsedEnd.operand1?.memory, endMemory.size == 64,
                  endMemory.base?.name == "rbx", endMemory.index == nil,
                  endMemory.displacement == 0x10,
                  compare.mnemonic == "cmp", let parsedCompare = compare.parsed,
                  parsedCompare.operands.count == 2,
                  parsedCompare.operand0?.register?.name == vectorRegister.name,
                  branch.isConditionalBranch else {
                continue
            }
            let upper = min(instructions.count - 2, index + 12)
            guard index + 4 <= upper else { continue }
            for inner in (index + 4)...upper {
                let loadAccelerator = instructions[inner]
                let storeAccelerator = instructions[inner + 1]
                guard loadAccelerator.mnemonic == "mov", let parsedLoad = loadAccelerator.parsed,
                      parsedLoad.operands.count == 2,
                      let acceleratorRegister = parsedLoad.operand0?.register, acceleratorRegister.width == 64,
                      let acceleratorSource = parsedLoad.operand1?.memory, acceleratorSource.size == 64,
                      acceleratorSource.base?.name == "rbp", acceleratorSource.index == nil,
                      acceleratorSource.displacement == -0x130,
                      storeAccelerator.mnemonic == "mov", let parsedStore = storeAccelerator.parsed,
                      parsedStore.operands.count == 2,
                      let destination = parsedStore.operand0?.memory,
                      destination.size == 64, destination.index == nil, destination.displacement == 0,
                      parsedStore.operand1?.register?.name == acceleratorRegister.name else {
                    continue
                }
                starts.insert(instructions[index].address)
            }
        }
        return starts.count == 1 ? starts.first : nil
    }

    /// True when the register tested by a null guard was last defined by loading
    /// the *AMD* accelerator slot `[rbp - 0x130]`. Such a check is the AMD
    /// accelerator's own null test, not the Intel-accelerator availability guard
    /// the fallback patch targets.
    private static func testedRegisterIsAMDAcceleratorLoad(_ register: Register,
                                                          before instruction: DecodedInstruction,
                                                          in analysis: FunctionAnalysis) -> Bool {
        for candidate in analysis.instructions.reversed() where candidate.address < instruction.address {
            guard let parsed = candidate.parsed, !parsed.operands.isEmpty,
                  let destination = parsed.operand0?.register,
                  destination.name == register.name else {
                continue
            }
            if candidate.mnemonic == "cmp" || candidate.mnemonic == "test" { continue }
            if candidate.mnemonic == "mov", parsed.operands.count == 2,
               let memory = parsed.operand1?.memory, memory.size == 64,
               memory.base?.name == "rbp", memory.index == nil, memory.displacement == -0x130 {
                return true
            }
            return false
        }
        return false
    }

    /// The "no Intel accelerator" null guard: `test r64, r64` immediately followed
    /// by a rel32 conditional branch whose taken target and fall-through path both
    /// converge on the same empty-return block.
    private static func acceleratorEmptyReturnBranches(_ analysis: FunctionAnalysis) -> [DecodedInstruction] {
        var candidates: [DecodedInstruction] = []
        for instruction in analysis.instructions where instruction.isConditionalBranch && instruction.length == 6 {
            guard let previous = analysis.previousInstruction(before: instruction),
                  previous.mnemonic == "test",
                  let parsedTest = previous.parsed, parsedTest.operands.count == 2,
                  let lhs = parsedTest.operand0?.register, let rhs = parsedTest.operand1?.register,
                  lhs.name == rhs.name, lhs.width == 64,
                  let target = instruction.directBranchTarget,
                  let targetBlock = analysis.blockIndex(forStart: target),
                  analysis.blocks[targetBlock].start == target,
                  let fallthroughInstruction = analysis.nextInstruction(after: instruction),
                  let fallthroughBlock = analysis.blockIndex(containing: fallthroughInstruction.address),
                  let last = analysis.instructions(inBlock: fallthroughBlock).last,
                  last.isJump, last.directBranchTarget == target,
                  !testedRegisterIsAMDAcceleratorLoad(lhs, before: instruction, in: analysis) else {
                continue
            }
            candidates.append(instruction)
        }
        return candidates
    }
