// Semantic patch data for the Chromium/Electron GL/Metal fix.  Unlike the exact-page tables these are
// instruction-context windows: a masked context identifies the site by its surrounding semantics, and
// the exact `find` bytes at `siteOffset` are verified before a same-length replacement is written.
//
// GL contexts were verified byte-for-byte against AMDRadeonX5000GLDriver from macOS 14 (page image),
// macOS 15.8.1 (full driver) and macOS 26.7.1 (full driver).  The only changing bytes are the RIP
// displacements, which are wildcarded.  The Metal contexts are per-AppleGVA/MTL driver variant groups
// (Sonoma, Sequoia, Tahoe gate/allow, and the Tahoe direct-field form); a group only applies when all
// of its sites match the same page, so a partial or foreign page is left untouched.
